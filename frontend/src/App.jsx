import { useEffect, useState } from "react";
import { explain, getHealth, getMetrics, getOptions } from "./api.js";

const LABELS = {
  gender: "Gender",
  race_ethnicity: "Race / ethnicity group",
  parental_level_of_education: "Parental education",
  lunch: "Lunch type",
  test_preparation_course: "Test preparation course",
};

const titleCase = (s) => s.replace(/(^|\s|\/)\w/g, (c) => c.toUpperCase());

function StudentForm({ options, onSubmit, loading, fieldErrors }) {
  const [form, setForm] = useState({ reading_score: 70, writing_score: 70 });

  useEffect(() => {
    const defaults = {};
    for (const [k, v] of Object.entries(options)) defaults[k] = v[0];
    setForm((f) => ({ ...defaults, ...f }));
  }, [options]);

  const set = (k) => (e) => setForm({ ...form, [k]: e.target.value });

  return (
    <form
      className="card form"
      onSubmit={(e) => {
        e.preventDefault();
        onSubmit({ ...form, reading_score: Number(form.reading_score), writing_score: Number(form.writing_score) });
      }}
    >
      <h2>Student profile</h2>
      {Object.keys(LABELS).filter((f) => options[f]).map((field) => [field, options[field]]).map(([field, values]) => (
        <label key={field}>
          <span>{LABELS[field] || field}</span>
          <select value={form[field] || ""} onChange={set(field)}>
            {values.map((v) => (
              <option key={v} value={v}>{titleCase(v)}</option>
            ))}
          </select>
          {fieldErrors[field] && <small className="error">{fieldErrors[field]}</small>}
        </label>
      ))}
      {["reading_score", "writing_score"].map((field) => (
        <label key={field}>
          <span>
            {field === "reading_score" ? "Reading score" : "Writing score"}
            <b>{form[field]}</b>
          </span>
          <input type="range" min="0" max="100" value={form[field]} onChange={set(field)} />
          {fieldErrors[field] && <small className="error">{fieldErrors[field]}</small>}
        </label>
      ))}
      <button disabled={loading}>{loading ? "Analysing…" : "Predict & explain"}</button>
    </form>
  );
}

function Result({ data }) {
  const { insights, assistant, total_ms } = data;
  const pct = insights.predicted_math_score;
  return (
    <div className="card result">
      <div className="score-row">
        <div className="score" style={{ "--pct": `${pct}%` }}>
          <span>{pct}</span>
          <small>/ 100</small>
        </div>
        <div>
          <div className={`band band-${insights.band.replace(" ", "-")}`}>{insights.band}</div>
          <p className="muted">
            Predicted math score · class average {insights.cohort_average} (
            {insights.difference_from_average >= 0 ? "+" : ""}
            {insights.difference_from_average})
          </p>
        </div>
      </div>

      <section>
        <h3>Explanation</h3>
        <p>{assistant.explanation}</p>
      </section>
      <section>
        <h3>Recommendations</h3>
        <p>{assistant.recommendations}</p>
        {insights.recommended_actions.length > 0 && (
          <ul className="actions">
            {insights.recommended_actions.map((a) => (
              <li key={a.id}>
                <span>{a.action}</span>
                <b>+{a.gain} → {a.predicted_score}</b>
              </li>
            ))}
          </ul>
        )}
      </section>
      <p className="muted tiny">
        Text generated by <code>{assistant.generated_by}</code> · {total_ms} ms
      </p>
    </div>
  );
}

function Leaderboard({ metrics }) {
  if (!metrics) return null;
  const max = Math.max(...metrics.leaderboard.map((r) => r.cv_r2_mean));
  return (
    <div className="card">
      <h2>Model selection</h2>
      <p className="muted">
        {metrics.leaderboard.length} models tuned with GridSearchCV and ranked by {metrics.selection}. Selected:{" "}
        <b>{metrics.best_model}</b> — test R² {metrics.test_metrics.r2}, MAE {metrics.test_metrics.mae}.
      </p>
      <table>
        <thead>
          <tr><th>Model</th><th>CV R²</th><th></th></tr>
        </thead>
        <tbody>
          {metrics.leaderboard.map((r) => (
            <tr key={r.model} className={r.model === metrics.best_model ? "best" : ""}>
              <td>{r.model}</td>
              <td>{r.cv_r2_mean.toFixed(3)} <span className="muted">±{r.cv_r2_std.toFixed(3)}</span></td>
              <td className="bar-cell"><div className="bar" style={{ width: `${(r.cv_r2_mean / max) * 100}%` }} /></td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export default function App() {
  const [options, setOptions] = useState({});
  const [metrics, setMetrics] = useState(null);
  const [health, setHealth] = useState(null);
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [fieldErrors, setFieldErrors] = useState({});

  useEffect(() => {
    getOptions().then(setOptions).catch((e) => setError(e.message));
    getMetrics().then(setMetrics).catch(() => {});
    getHealth().then(setHealth).catch(() => {});
  }, []);

  const submit = async (student) => {
    setLoading(true);
    setError("");
    setFieldErrors({});
    try {
      setResult(await explain(student));
    } catch (e) {
      setError(e.message);
      setFieldErrors(e.fields);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="page">
      <header>
        <h1>Student Performance Predictor</h1>
        <p className="muted">
          ML prediction of math scores with an NLP academic assistant that explains the result and suggests next steps.
        </p>
        {health && (
          <p className="tiny muted">
            Assistant: {health.assistant.backend}
            {health.assistant.model ? ` (${health.assistant.model})` : ""}
          </p>
        )}
      </header>
      {error && <div className="alert">{error}</div>}
      <main>
        <StudentForm options={options} onSubmit={submit} loading={loading} fieldErrors={fieldErrors} />
        <div className="stack">
          {result ? <Result data={result} /> : (
            <div className="card empty">Fill in the profile and press <b>Predict &amp; explain</b>.</div>
          )}
          <Leaderboard metrics={metrics} />
        </div>
      </main>
    </div>
  );
}
